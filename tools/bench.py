#!/usr/bin/env python3
"""Run bench/bench.py on unix builds and boards, and write the report.

  tools/bench.py run --unix standard [--label unix-x86]      # a unix build
  tools/bench.py run --port /dev/ttyUSB0 --label esp32-spiram  # a board
  tools/bench.py report                                       # rewrite docs/BENCHMARKS.md

Each run is saved as docs/benchmarks/<label>.json; the report puts all the
saved runs side by side. On a board, the test firmware must be flashed (it
has umsgpack frozen in): tools/build-esp32.sh BOARD [VARIANT] --test.
"""

import argparse
import datetime
import json
import os
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "docs" / "benchmarks"
REPORT = ROOT / "docs" / "BENCHMARKS.md"
BENCH = ROOT / "bench" / "bench.py"


def run_unix(flavour):
    exe = ROOT / "build" / f"unix-{flavour}" / "micropython"
    env = dict(os.environ, MICROPYPATH=f"{ROOT / 'third_party/micropython-msgpack'}:.frozen")
    return subprocess.run(
        [str(exe), "-X", "heapsize=64M", str(BENCH)],
        capture_output=True, text=True, env=env, check=True,
    ).stdout  # fmt: skip


def run_board(port):
    mpremote = ROOT / ".venv" / "bin" / "mpremote"
    return subprocess.run(
        [str(mpremote), "connect", port, "run", str(BENCH)],
        capture_output=True, text=True, check=True, timeout=3600,
    ).stdout  # fmt: skip


def cmd_run(args):
    out = run_unix(args.unix) if args.unix else run_board(args.port)
    rows = [json.loads(line[6:]) for line in out.splitlines() if line.startswith("BENCH {")]
    info = next(
        json.loads(line[11:]) for line in out.splitlines() if line.startswith("BENCH-INFO")
    )
    if not rows:
        sys.exit("no results:\n" + out)
    label = args.label or (f"unix-{args.unix}" if args.unix else "board")
    host = f"{platform.system()} {platform.machine()}" if args.unix else None
    doc = {
        "label": label,
        "description": args.description or info["platform"],
        "platform": info["platform"],
        "host": host,
        "float": info["float"],
        "date": datetime.date.today().isoformat(),
        "results": rows,
    }
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / f"{label}.json").write_text(json.dumps(doc, indent=1) + "\n")
    print(f"saved docs/benchmarks/{label}.json ({len(rows)} results)")
    cmd_report(args)


def fmt_us(us):
    return f"{us:.1f}" if us < 100 else f"{us:.0f}"


def ratio(a, b):
    return f"**{b / a:.1f}x**" if a > 0 else "-"


# Order and names of the runs in the report; other runs follow, by label.
ORDER = {
    "esp32": "ESP32, internal RAM",
    "esp32-psram": "ESP32, PSRAM",
    "esp32-p4": "ESP32-P4",
    "unix-macos": "unix port, Apple Silicon",
}


SIZES = RESULTS / "firmware-size.json"


def load_runs():
    runs = [json.loads(p.read_text()) for p in RESULTS.glob("*.json") if p != SIZES]
    rank = list(ORDER)
    runs.sort(
        key=lambda r: (rank.index(r["label"]) if r["label"] in rank else len(rank), r["label"])
    )
    return runs


def title(run):
    return ORDER.get(run["label"], run["label"])


def cmd_report(args):
    runs = load_runs()
    lines = [
        "# Benchmarks",
        "",
        "Generated by `tools/bench.py report` from the runs saved in",
        "[`docs/benchmarks/`](benchmarks/). The program is",
        "[`bench/bench.py`](../bench/bench.py); see [TESTING.md](TESTING.md#benchmarks)",
        "for how to run it and how to read the figures.",
        "",
        "- **msgpackc**: this module (C).",
        "- **umsgpack**: [Peter Hinch's umsgpack](https://github.com/peterhinch/micropython-msgpack)"
        " (pure Python; frozen bytecode on the boards, the fastest way to run it).",
        "- **json**: MicroPython's built-in `json` module (C), for reference.",
        "- *time* is per call, in microseconds (median of 5 runs); *alloc* is the heap",
        "  allocated by one call, in bytes; *speed-up* is umsgpack time / msgpackc time.",
        "",
    ]
    for run in runs:
        rows = run["results"]
        by = {(r["payload"], r["lib"]): r for r in rows}
        payloads = list(dict.fromkeys(r["payload"] for r in rows))
        lines += [
            f"## {title(run)}",
            "",
            f"{run['description']} — MicroPython `{run['platform']}`, floats: {run['float']}"
            + (f", host: {run['host']}" if run.get("host") else "")
            + f", {run['date']}.",
            "",
            "| payload | size | msgpackc dumps | umsgpack dumps | speed-up | json dumps"
            " | msgpackc loads | umsgpack loads | speed-up | json loads |",
            "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
        ]
        for p in payloads:
            c, u, j = by.get((p, "msgpackc")), by.get((p, "umsgpack")), by.get((p, "json"))
            lines.append(
                f"| {p} | {c['size']} B"
                f" | {fmt_us(c['dumps_us'])} | {fmt_us(u['dumps_us']) if u else '-'}"
                f" | {ratio(c['dumps_us'], u['dumps_us']) if u else '-'}"
                f" | {fmt_us(j['dumps_us']) if j else '-'}"
                f" | {fmt_us(c['loads_us'])} | {fmt_us(u['loads_us']) if u else '-'}"
                f" | {ratio(c['loads_us'], u['loads_us']) if u else '-'}"
                f" | {fmt_us(j['loads_us']) if j else '-'} |"
            )
        lines += [
            "",
            "Heap allocated per call (bytes) and encoded size:",
            "",
            "| payload | msgpackc dumps | umsgpack dumps | json dumps | msgpackc loads"
            " | umsgpack loads | json loads | json size |",
            "|---|--:|--:|--:|--:|--:|--:|--:|",
        ]
        for p in payloads:
            c, u, j = by.get((p, "msgpackc")), by.get((p, "umsgpack")), by.get((p, "json"))
            lines.append(
                f"| {p} | {c['dumps_alloc']} | {u['dumps_alloc'] if u else '-'}"
                f" | {j['dumps_alloc'] if j else '-'} | {c['loads_alloc']}"
                f" | {u['loads_alloc'] if u else '-'} | {j['loads_alloc'] if j else '-'}"
                f" | {str(j['size']) + ' B' if j else '-'} |"
            )
        lines.append("")
    if SIZES.exists():
        sizes = json.loads(SIZES.read_text())
        lines += [
            "## Firmware size",
            "",
            f"{sizes['note']}. *text*, *data* and *bss* are the sections of the module's object"
            " file: *bss* 0 means no RAM is reserved.",
            "",
            "| firmware | with msgpackc | without | difference | text | data | bss |",
            "|---|--:|--:|--:|--:|--:|--:|",
        ]
        for z in sizes["sizes"]:
            lines.append(
                f"| {z['target']} | {z['with']:,} B | {z['without']:,} B"
                f" | **+{z['with'] - z['without']:,} B** | {z['text']:,} | {z['data']} | {z['bss']} |"
            )
        lines.append("")
    REPORT.write_text("\n".join(lines))
    print(f"wrote {REPORT.relative_to(ROOT)} ({len(runs)} runs)")
    readme_summary(runs)


SUMMARY_PAYLOAD = "telemetry x20"
README = ROOT / "README.md"


def readme_summary(runs):
    """The table between the BENCH-SUMMARY markers of README.md."""
    start, end = "<!-- BENCH-SUMMARY -->", "<!-- /BENCH-SUMMARY -->"
    text = README.read_text()
    if start not in text:
        return
    lines = [
        start,
        "",
        "Time to pack and unpack a list of 20 telemetry records (1 KiB), and heap"
        " allocated, per call ([all the figures](docs/BENCHMARKS.md)):",
        "",
        "| | msgpackc dumps | umsgpack dumps | | msgpackc loads | umsgpack loads | |",
        "|---|--:|--:|--:|--:|--:|--:|",
    ]
    for run in runs:
        by = {(r["payload"], r["lib"]): r for r in run["results"]}
        c, u = by.get((SUMMARY_PAYLOAD, "msgpackc")), by.get((SUMMARY_PAYLOAD, "umsgpack"))
        if not c or not u:
            continue
        lines.append(
            f"| {title(run)} | **{fmt_us(c['dumps_us'])} µs**, {c['dumps_alloc']} B"
            f" | {fmt_us(u['dumps_us'])} µs, {u['dumps_alloc']} B"
            f" | {ratio(c['dumps_us'], u['dumps_us'])} faster"
            f" | **{fmt_us(c['loads_us'])} µs**, {c['loads_alloc']} B"
            f" | {fmt_us(u['loads_us'])} µs, {u['loads_alloc']} B"
            f" | {ratio(c['loads_us'], u['loads_us'])} faster |"
        )
    lines += ["", end]
    head, rest = text.split(start, 1)
    tail = rest.split(end, 1)[1] if end in rest else rest
    README.write_text(head + "\n".join(lines) + tail)
    print("updated the summary in README.md")


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    where = r.add_mutually_exclusive_group(required=True)
    where.add_argument("--unix", metavar="FLAVOUR", help="a build of tools/build-unix.sh")
    where.add_argument("--port", help="serial port of a board with the test firmware")
    r.add_argument("--label", help="name of the run (file name of the results)")
    r.add_argument("--description", help="one line describing the hardware")
    sub.add_parser("report")
    args = ap.parse_args()
    (cmd_run if args.cmd == "run" else cmd_report)(args)


if __name__ == "__main__":
    main()
